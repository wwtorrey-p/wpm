"""Builds the web UI into data/ before the firmware, which embeds those files."""
import os
import shutil
import subprocess

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

project = env.subst("$PROJECT_DIR")  # noqa: F821
web = os.path.join(project, "web")
index = os.path.join(project, "data", "index.html")

def run(cmd):
    # Vite prints non-ASCII symbols that PlatformIO cannot echo when its output is redirected on Windows.
    result = subprocess.run(cmd, cwd=web, shell=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                            text=True, encoding="utf-8", errors="replace")
    print(result.stdout.encode("ascii", "replace").decode("ascii"))
    if result.returncode != 0:
        raise subprocess.CalledProcessError(result.returncode, cmd)


try:
    if not os.path.isdir(os.path.join(web, "node_modules")):
        run("npm install")
    run("npm run build")
except (subprocess.CalledProcessError, OSError) as err:
    if os.path.exists(index):
        print("WARNING: web UI build failed (%s); embedding the existing data/ files" % err)
    else:
        print("ERROR: web UI build failed and data/index.html does not exist: %s" % err)
        env.Exit(1)  # noqa: F821

# Served paths, MIME types and the data/ file behind each. The UI is compiled in as plain C++ arrays
# because the platform's embed options do not link reliably with a PlatformIO ESP-IDF project.
ASSETS = [
    ("index.html", "text/html", ["/", "/index.html"]),
    ("app.js", "text/javascript", ["/app.js"]),
    ("index.css", "text/css", ["/index.css"]),
]


def generate():
    lines = ['// Generated by tools/build_web.py. Do not edit.', '#include "web_assets.h"', ""]
    table = []
    for i, (name, mime, paths) in enumerate(ASSETS):
        with open(os.path.join(project, "data", name), "rb") as fh:
            data = fh.read()
        body = ",".join("0x%02x" % b for b in data) if data else "0"
        lines.append("static const unsigned char d%d[] = {%s};" % (i, body))
        for p in paths:
            table.append('    {"%s", "%s", d%d, %d},' % (p, mime, i, len(data)))
    lines += ["", "const WebAsset kWebAssets[] = {"] + table + ["};",
              "const size_t kWebAssetCount = %d;" % len(table), ""]
    return "\n".join(lines)


out_dir = os.path.join(project, "src", "generated")
out = os.path.join(out_dir, "web_assets.cpp")
try:
    content = generate()
except OSError as err:
    print("ERROR: cannot read the built web UI files in data/: %s" % err)
    env.Exit(1)  # noqa: F821

os.makedirs(out_dir, exist_ok=True)
old = None
if os.path.exists(out):
    with open(out, "r", encoding="ascii") as fh:
        old = fh.read()
if old != content:  # rewriting an identical file would force a recompile
    with open(out, "w", encoding="ascii", newline="\n") as fh:
        fh.write(content)
